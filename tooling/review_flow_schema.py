#!/usr/bin/env python3
"""Emit or verify the review-flow schemas against the pydantic models.

`schemas/review-flow.schema.json` projects `ReviewFlow` and `schemas/review-rules.schema.json`
projects `RulesFile`, both from `features/common/skills/review-flow/scripts/
review_flow_model.py`, loaded by path from the audited `--root` tree.

Usage: review_flow_schema.py [--root <dir>] [--check]
  (default) write both schemas canonically
  --check   do not write; exit 1 on any difference, printing the first differing JSON pointer
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any, Dict

from pydantic.json_schema import GenerateJsonSchema

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "engine"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import badger_lib as bl  # pylint: disable=wrong-import-position
from task_plan_schema import canonical_text, first_difference  # pylint: disable=wrong-import-position

MODEL_RELPATH = "features/common/skills/review-flow/scripts/review_flow_model.py"
DIALECT = GenerateJsonSchema.schema_dialect
BOUNDARY = (
    " Generated by tooling/review_flow_schema.py from the pydantic model in "
    f"{MODEL_RELPATH}. Cross-field rules are pydantic-only and enforced on every load, not by "
    "this artifact."
)
SCHEMAS = {
    "schemas/review-flow.schema.json": (
        "ReviewFlow",
        "The persisted review flow of one pull request: rounds, findings, dispositions and "
        "phase history. Not expressed here: the fingerprint must equal "
        "sha256(kind|path|symbol[|anchor]), phase ranks gate lane runs, dispositions and "
        "publication, only the last round may be open, and each round's history replays along "
        "the declared transitions to its phase."),
    "schemas/review-rules.schema.json": (
        "RulesFile",
        "Learned review rules and project facts (.ai-badger/review/rules.json). Not expressed "
        "here: activation proof per activated_by, independent threads, ascending unique ids, "
        "and the DEFENSIVE downgrade rule."),
}


def load_model(root: Path):
    """Import the review-flow model from `root` by path (never from an installed package)."""
    path = root / MODEL_RELPATH
    spec = importlib.util.spec_from_file_location("aib_review_flow_model", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load the review-flow model from {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def build_schemas(model: Any) -> Dict[str, Dict[str, Any]]:
    """Each schema relpath mapped to its canonical schema object."""
    built = {}
    for relpath, (title, description) in SCHEMAS.items():
        schema = getattr(model, title).model_json_schema(mode="validation")
        schema["$schema"] = DIALECT
        schema["$id"] = f"https://github.com/Arasz/ai-badger/{relpath}"
        schema["title"] = title
        schema["description"] = description + BOUNDARY
        built[relpath] = schema
    return built


def _check(root: Path, relpath: str, generated: Dict[str, Any]) -> bool:
    path = root / relpath
    if not path.is_file():
        print(f"STALE {relpath}: missing; run tooling/review_flow_schema.py")
        return False
    difference = first_difference(json.loads(path.read_text(encoding="utf-8")), generated)
    if difference is not None:
        pointer, got, want = difference
        print(f"STALE {relpath}: first difference at {pointer}")
        print(f"  checked in: {json.dumps(got, ensure_ascii=False)}")
        print(f"  generated:  {json.dumps(want, ensure_ascii=False)}")
        print("run tooling/review_flow_schema.py to regenerate")
        return False
    print(f"ok {relpath} matches the model")
    return True


def main(argv=None) -> int:
    """CLI entry point: write the schemas, or `--check` them against the model."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 when a checked-in schema differs")
    parser.add_argument("--root", help="Framework root (default: auto-detect).")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve() if args.root else bl.find_root()
    built = build_schemas(load_model(root))
    if args.check:
        results = [_check(root, relpath, schema) for relpath, schema in built.items()]
        return 0 if all(results) else 1
    for relpath, schema in built.items():
        path = root / relpath
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(canonical_text(schema), encoding="utf-8")
        print(f"wrote {relpath}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
