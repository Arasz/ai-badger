# Red-proofs: one per --check violation class, plus zero-rule and stale-walk.
# ---------------------------------------------------------------------------

def _append_rules(text: str, n: int, start: int) -> str:
    """n mechanically-valid, minimal T1 rules (own pass/order/phase, no parent needed)."""
    blocks = []
    for i in range(start, start + n):
        rid = f"T1-FIL-{i:02d}"
        blocks.append(
            f"\n**`{rid}` — Filler rule {i}.**\n"
            "- *design:* filler.\n- *review:* filler.\n- *check:* argued.\n"
            "- **severity:** minor · **evidence:** weak · **flag:** argued\n"
            f"- *meta:* pass=0 order={i} phase=review-only\n"
        )
    return text + "".join(blocks)


def test_l1_cap_violation(rules_index, root, tmp_path, capsys):
    fixture = _copy_fixture(root, tmp_path, "l1cap")
    universal = fixture / "references" / "universal.md"
    original = universal.read_text(encoding="utf-8")
    # 2 existing L1 rules + 39 filler = 41 > cap of 40.
    universal.write_text(_append_rules(original, 39, start=1), encoding="utf-8")

    rc, out = _run_captured(capsys, rules_index, fixture, "--check")
    assert rc == 1
    assert "[L1-CAP]" in out
    assert "41 exceeds the cap of 40" in out

    universal.write_text(original, encoding="utf-8")
    rc, out = _run_captured(capsys, rules_index, fixture, "--check")
    assert rc == 0


