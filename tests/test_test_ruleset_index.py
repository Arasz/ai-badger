def test_meta_line_and_l2_no_phase_are_parsed_correctly(rules_index, root, tmp_path):
    """The real ruleset's convention: one `*meta:* pass=N order=M [phase=P]` bullet line, not
    the individual `pass:`/`order:`/`phase:` bullets an earlier draft of this fixture used."""
    fixture = _copy_fixture(root, tmp_path)
    _run(rules_index, fixture)
    index = json.loads((fixture / "rules.json").read_text(encoding="utf-8"))
    by_id = {r["id"]: r for r in index}
    assert by_id["T1-AAA-01"]["pass"] == 1
    assert by_id["T1-AAA-01"]["order"] == 1
    assert by_id["T1-AAA-01"]["phase"] == "6"
    assert by_id["T1-AAA-02"]["phase"] == "review-only"
    # T2-WID-01 carries pass/order (for the review walk) but no phase (§6: only L1 designs).
    assert by_id["T2-WID-01"]["pass"] == 1
    assert by_id["T2-WID-01"]["phase"] is None


