def test_planted_bogus_id_in_a_walk_is_caught_as_drift(rules_index, root, tmp_path, capsys):
    """SYNTHESIS ruling C: the gate's own test plants a bogus rule id in a walk, asserts red,
    removes it, asserts green — a walk that has only ever passed --check is not a check."""
    fixture = _copy_fixture(root, tmp_path, "bogusid")
    _run(rules_index, fixture)  # establish the committed baseline

    walk = fixture / "references" / "walk-review.md"
    original = walk.read_text(encoding="utf-8")
    walk.write_text(original + "- **T1-ZZZ-99** — a rule that does not exist. "
                                "(severity: blocker, flag: auto)\n",
                     encoding="utf-8")

    rc, out = _run_captured(capsys, rules_index, fixture, "--check")
    assert rc == 1
    assert "[STALE] references/walk-review.md" in out

    walk.write_text(original, encoding="utf-8")
    rc, out = _run_captured(capsys, rules_index, fixture, "--check")
    assert rc == 0


