"""Tests for review-tests/scripts/rules_index.py against tests/fixtures/test_ruleset_min/.

Every test copies the fixture into tmp_path first — never runs the script against the real
fixture directory in place (the suite's own write-isolation guard forbids writing inside a real
checkout; see conftest._test_write). "Red" tests plant one defect, assert --check fails and
names it, then assert the unmodified copy is clean — the pairing IS the red-proof
(prove-the-check-fails): a check that has only ever passed is not a check.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

SCRIPT = "features/common/skills/review-tests/scripts/rules_index.py"
FIXTURE = "tests/fixtures/test_ruleset_min"


@pytest.fixture
def rules_index(load_script):
    return load_script(SCRIPT)


def _copy_fixture(root: Path, tmp_path: Path, name: str = "min") -> Path:
    dest = tmp_path / name
    shutil.copytree(root / FIXTURE, dest)
    return dest


def _run(rules_index, fixture_root: Path, *extra: str) -> int:
    return rules_index.main(["--root", str(fixture_root), *extra])


def _run_captured(capsys, rules_index, fixture_root: Path, *extra: str):
    rc = _run(rules_index, fixture_root, *extra)
    return rc, capsys.readouterr().out


# ---------------------------------------------------------------------------
# Baseline: the fixture as committed is clean, and generation is idempotent.
# ---------------------------------------------------------------------------

def test_check_passes_on_the_clean_fixture(rules_index, root, tmp_path, capsys):
    fixture = _copy_fixture(root, tmp_path)
    rc, out = _run_captured(capsys, rules_index, fixture, "--check")
    assert rc == 0
    assert "up to date" in out


def test_generation_is_idempotent(rules_index, root, tmp_path):
    fixture = _copy_fixture(root, tmp_path)
    rc1 = _run(rules_index, fixture)
    first = {
        p.relative_to(fixture): p.read_text(encoding="utf-8")
        for p in (fixture / "rules.json",
                  fixture / "references" / "walk-review.md",
                  fixture / "references" / "walk-design.md")
    }
    rc2 = _run(rules_index, fixture)
    second = {
        p.relative_to(fixture): p.read_text(encoding="utf-8")
        for p in (fixture / "rules.json",
                  fixture / "references" / "walk-review.md",
                  fixture / "references" / "walk-design.md")
    }
    assert rc1 == 0
    assert rc2 == 0
    assert first == second


